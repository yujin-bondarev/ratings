CREATE TABLE dean_logs
(
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    source_id BIGINT,
    status    SMALLINT DEFAULT 0,
    created   TIMESTAMP WITHOUT TIME ZONE,
    updated   TIMESTAMP WITHOUT TIME ZONE,
    ip        VARCHAR(255),
    jti       VARCHAR(255),
    username  VARCHAR(255),
    url       VARCHAR(255),
    params    VARCHAR(255),
    method    VARCHAR(255),
    body      VARCHAR(255),
    CONSTRAINT pk_dean_logs PRIMARY KEY (id)
);

CREATE TABLE emp_params
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    source_id  BIGINT,
    status     SMALLINT DEFAULT 0,
    created    TIMESTAMP WITHOUT TIME ZONE,
    updated    TIMESTAMP WITHOUT TIME ZONE,
    param_id   BIGINT                                  NOT NULL,
    value      DOUBLE PRECISION,
    teacher_id BIGINT                                  NOT NULL,
    CONSTRAINT pk_emp_params PRIMARY KEY (id)
);

CREATE TABLE param
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    source_id      BIGINT,
    status         SMALLINT DEFAULT 0,
    created        TIMESTAMP WITHOUT TIME ZONE,
    updated        TIMESTAMP WITHOUT TIME ZONE,
    name           VARCHAR(255)                            NOT NULL,
    param_group_id BIGINT,
    type           VARCHAR(255)                            NOT NULL,
    weight         DOUBLE PRECISION                        NOT NULL,
    comment        VARCHAR(255),
    description    VARCHAR(255),
    CONSTRAINT pk_param PRIMARY KEY (id)
);

CREATE TABLE param_groups
(
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    source_id BIGINT,
    status    SMALLINT DEFAULT 0,
    created   TIMESTAMP WITHOUT TIME ZONE,
    updated   TIMESTAMP WITHOUT TIME ZONE,
    name      VARCHAR(255)                            NOT NULL,
    CONSTRAINT pk_param_groups PRIMARY KEY (id)
);

CREATE TABLE workloads
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    source_id      BIGINT,
    status         SMALLINT DEFAULT 0,
    created        TIMESTAMP WITHOUT TIME ZONE,
    updated        TIMESTAMP WITHOUT TIME ZONE,
    year           INTEGER,
    semester       VARCHAR(255),
    activity_type  VARCHAR(255),
    hours          DOUBLE PRECISION,
    publications   DOUBLE PRECISION,
    rating_value   DOUBLE PRECISION,
    date_submitted date,
    CONSTRAINT pk_workloads PRIMARY KEY (id)
);

ALTER TABLE emp_params
    ADD CONSTRAINT FK_EMP_PARAMS_ON_PARAM FOREIGN KEY (param_id) REFERENCES param (id);

ALTER TABLE param
    ADD CONSTRAINT FK_PARAM_ON_PARAM_GROUP FOREIGN KEY (param_group_id) REFERENCES param_groups (id);